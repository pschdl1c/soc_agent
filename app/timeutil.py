"""
Канонизация меток времени событий - лист-модуль без импортов из app (как app/timespan.py).

Зачем отдельный модуль: одну и ту же метку времени независимо приводят к сравнимому виду
СРАЗУ ТРИ подсистемы - app/store.py (колонка events.event_time и леджер rule_hits.event_time
на записи, плюс границы диапазона на чтении), app/detection/correlation.py (окно корреляции
считается по тем же нормализованным строкам) и app/main.py (границы time_from/time_to из UI).
Раньше это была однострочная трансформация `replace(" ", "T").replace("Z", "")`, продублированная
в store.py и correlation.py, а в SQL - ещё и третьей копией прямо в тексте запроса. Три копии
разъезжались на трёх классах входа:

  1. Граница из параметра НЕ нормализовалась вообще: `time_from=2026-09-05 09:00:00` (с пробелом,
     ровно тот формат, что показывает колонка «Время») не находил ничего.
  2. Формат источника с дробной частью терял событие ровно на верхней границе:
     "...T21:01:30.113" > "...T21:01:30" при строковом сравнении.
  3. Смещения не конвертировались: "21:00:00+03:00" и "18:00:00Z" - один момент времени, но
     сортировались и фильтровались как разные, на три часа врозь.

Решение - ОДНА каноническая форма, в которой метка ЛОЖИТСЯ НА ДИСК (store.store_events), и
ей же приводятся границы запроса: наивный (без tzinfo) ISO по UTC, "YYYY-MM-DDTHH:MM:SS[.ffffff]".
Тот же формат, что у alerts.created_at (models.utcnow_naive) и у границ из UI (timeParams()
в index.html - специально без 'Z'/offset). Лексикографическое сравнение такой строки совпадает
с хронологическим, поэтому SQL сравнивает колонку НАПРЯМУЮ (`event_time BETWEEN ? AND ?`), без
обёртки replace(...) - а значит планировщик наконец может использовать idx_events_time как
range-scan (колонка, обёрнутая в функцию, индекс так не использует).

Сырое значение источника при этом не теряется - оно как было, так и остаётся в events.raw_json.
"""
from __future__ import annotations

from datetime import datetime, timezone

# Хвост-сентинель для ВЕРХНЕЙ границы диапазона (см. normalize_time_bound). U+FFFF в UTF-8 -
# EF BF BF, что больше любого ASCII-байта, а канонические метки времени состоят исключительно
# из ASCII (цифры, '-', ':', '.', 'T'): строка "2026-09-05T21:01:30" + сентинель больше любого
# продолжения того же префикса (".113000", ".5" и т.п.) и при этом меньше следующей секунды
# "2026-09-05T21:01:31". Так граница с точностью до секунды включает событие этой же секунды
# с дробной частью - иначе оно молча выпадало из диапазона.
_UPPER_SENTINEL = chr(0xFFFF)


def normalize_event_time(value: str | None) -> str | None:
    """Каноническая форма метки времени: наивный ISO по UTC ("YYYY-MM-DDTHH:MM:SS[.ffffff]").

    Понимает всё, что реально приходит от источников: "YYYY-MM-DD HH:MM:SS[.fff]" (EVTX через
    Zircolite - пробел, без зоны), ISO с "T" и суффиксом "Z" (Sysmon/JSON), ISO со смещением
    ("+03:00" - будущий форвардер с ВМ, Этап 5), ISO без зоны, и "YYYY-MM-DD HH:MM:SS +0300" -
    TimeCreated от Fluent Bit winevtlog (пробел ПЕРЕД смещением). Aware-значения переводятся в UTC
    и теряют tzinfo; naive считаются УЖЕ UTC (единственное возможное допущение - зоны в метке
    нет и взять её неоткуда).

    Нераспознанный формат возвращается по СТАРОМУ правилу (пробел -> "T", "Z" отброшен), а не
    роняет ingest: неизвестная метка времени - не повод потерять событие. На вход всегда
    приходит str|None (fields.first_present приводит значение поля к строке).
    """
    if value is None:
        return None
    raw = value.strip()
    if not raw:
        return value
    try:
        # Только ПЕРВЫЙ пробел (дата/время) - второй, перед смещением у TimeCreated Fluent Bit,
        # fromisoformat понимает сам; замена всех пробелов давала "…T02:08:49T+0300" и фолбэк.
        dt = datetime.fromisoformat(raw.replace(" ", "T", 1))
    except ValueError:
        return raw.replace(" ", "T").replace("Z", "")
    if dt.tzinfo is not None:
        dt = dt.astimezone(timezone.utc).replace(tzinfo=None)
    return dt.isoformat()


def normalize_time_bound(value: str | None, upper: bool = False) -> str | None:
    """Приводит границу диапазона (time_from/time_to из query-параметра) к той же канонической
    форме, что и колонка. Пустая/отсутствующая граница - None (фильтр не накладывается).

    upper=True добавляет хвост-сентинель: верхняя граница трактуется как ВКЛЮЧАЮЩАЯ всё, что
    её продолжает - "…T21:01:30" накрывает и "…T21:01:30.113000". Нижней границе сентинель не
    нужен и вреден (он бы, наоборот, отрезал события той же секунды с дробной частью).
    """
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    normalized = normalize_event_time(text) or text
    return normalized + _UPPER_SENTINEL if upper else normalized
