"""
Счётчики изменений для автообновления списков в UI (Этап 2 дорожной карты, шаг без SSE).

Лист-модуль без импортов проекта. Состояние живёт ТОЛЬКО В ПАМЯТИ процесса: ingest пишет
алерты/инциденты из фонового потока IngestWorker, а UI раз в несколько секунд спрашивает
`GET /updates` и сравнивает ответ со своим предыдущим снимком (см. pollUpdates в
app/static/index.html). В БД за этим лезть незачем и нельзя:

* дорого - на каждый поллинг это COUNT(*) с теми же фильтрами, что у списка;
* НЕТОЧНО - у `alerts` нет `updated_at` (см. _SCHEMA в app/store.py), а повторное
  срабатывание правила ИНКРЕМЕНТИРУЕТ event_count существующей строки (дедуп по dedup_key,
  см. app/detection/normalize.py). По "максимальному created_at" такое изменение не видно
  вообще, хотя список в UI поменялся.

Поэтому у каждого канала ДВА числа:

* ``version`` - монотонный счётчик ЛЮБОГО изменения канала (новая строка, инкремент
  event_count у существующей, смена статуса/вердикта, удаление источника). По нему UI
  решает, что список пора перечитать.
* ``created`` - сколько строк реально СОЗДАНО. По разнице двух снимков UI показывает
  "N новых"; если version изменилась, а created нет - значит поменялись уже существующие
  строки, и в бейдже просто "обновления".

``epoch`` - идентификатор запуска процесса. После рестарта счётчики начинаются с нуля, и без
epoch клиент со снимком version=42 молча не заметил бы, что сервер уехал на version=1.

Бампится В ТОЧКАХ ЗАПИСИ (app/main.py, app/detection/correlation.py, app/incidents.py), а не
в одном месте оркестрации: пишут в alerts/incidents все трое, и централизовать это можно
было бы только сквозным протаскиванием счётчиков через возвращаемые значения.

ОГРАНИЧЕНИЕ: работает, пока процесс ОДИН (uvicorn без --workers, см. Dockerfile). При
нескольких воркерах у каждого будет свой счётчик, и UI начнёт дёргать список на каждом
поллинге, попадая то в один процесс, то в другой. Тогда состояние переезжает в общее место
(та же БД / redis) - вместе с переходом на SSE, там ровно та же развилка.
"""
from __future__ import annotations

import threading
import uuid

# Каналы = списки в UI, которые умеют автообновляться.
CHANNELS = ("alerts", "incidents")

_lock = threading.Lock()
_epoch = uuid.uuid4().hex[:16]
_state: dict[str, dict[str, int]] = {ch: {"version": 0, "created": 0} for ch in CHANNELS}


def bump(channel: str, created: int = 0) -> None:
    """Отмечает изменение канала: +1 к version всегда, +created к счётчику созданных строк.

    Зовётся из фонового потока ingest наравне с HTTP-обработчиками - отсюда лок (сам GIL
    гарантий на "прочитать-изменить-записать" не даёт). Неизвестный канал игнорируется молча:
    счётчик - вспомогательная штука для UI, ронять из-за него запись алерта нечего."""
    if channel not in _state:
        return
    with _lock:
        _state[channel]["version"] += 1
        if created:
            _state[channel]["created"] += created


def snapshot() -> dict:
    """Текущий снимок для GET /updates: {"epoch": ..., "alerts": {...}, "incidents": {...}}."""
    with _lock:
        return {"epoch": _epoch, **{ch: dict(counters) for ch, counters in _state.items()}}


def _reset() -> None:
    """Тест-хук: обнуляет счётчики и выдаёт новый epoch (модульное состояние глобально)."""
    global _epoch
    with _lock:
        _epoch = uuid.uuid4().hex[:16]
        for counters in _state.values():
            counters["version"] = 0
            counters["created"] = 0
